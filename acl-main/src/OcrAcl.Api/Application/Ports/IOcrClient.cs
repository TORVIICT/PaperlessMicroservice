namespace OcrAcl.Application.Ports;

using OcrAcl.Application.Models;

/// <summary>
/// Transport-agnostic port for OCR service operations.
/// Implemented by Infrastructure adapters (HTTP polling or MassTransit).
/// Use cases depend only on this interface.
/// </summary>
public interface IOcrClient
{
    Task<OcrDocument> GetDocumentAsync(Guid documentId, CancellationToken cancellationToken = default);

    Task<OcrDocumentText> GetTextAsync(Guid documentId, CancellationToken cancellationToken = default);

    Task<Stream> DownloadOriginalAsync(Guid documentId, CancellationToken cancellationToken = default);

    /// <summary>
    /// Submits a document for OCR processing.
    /// </summary>
    /// <param name="fileContent">The file content as a stream.</param>
    /// <param name="fileName">Original file name.</param>
    /// <param name="contentType">MIME type (application/pdf, image/png, image/jpeg).</param>
    /// <param name="clientReference">Opaque reference generated by the ACL (≤ 64 chars, [a-z0-9_-]).</param>
    /// <param name="language">OCR language (ISO 639-2/3, e.g., "spa", "eng").</param>
    /// <param name="mode">OCR mode (skip, redo, force).</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>The created OCR job with jobId and initial status.</returns>
    Task<OcrJob> SubmitAsync(
        Stream fileContent,
        string fileName,
        string contentType,
        string clientReference,
        string language,
        string mode,
        CancellationToken cancellationToken = default);

    /// <summary>
    /// Gets the status and result of an OCR job by jobId.
    /// </summary>
    /// <param name="jobId">The OCR job identifier.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>The OCR job with current status and result/error if terminal.</returns>
    Task<OcrJob> GetJobAsync(Guid jobId, CancellationToken cancellationToken = default);

    /// <summary>
    /// Gets the status and result of an OCR job by polling URL (from Location header).
    /// </summary>
    /// <param name="pollingUrl">The full polling URL from the 202 Location header.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>The OCR job with current status and result/error if terminal.</returns>
    Task<OcrJob> GetJobByUrlAsync(string pollingUrl, CancellationToken cancellationToken = default);

    /// <summary>
    /// Downloads the searchable PDF/A archive for a completed job.
    /// </summary>
    /// <param name="jobId">The OCR job identifier.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>The archive stream (application/pdf).</returns>
    Task<Stream> DownloadArchiveAsync(Guid jobId, CancellationToken cancellationToken = default);

    /// <summary>
    /// Downloads the first-page thumbnail for a completed job.
    /// Internal use only; thumbnail URL never exposed to Gateway/Frontend.
    /// </summary>
    /// <param name="jobId">The OCR job identifier.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>The thumbnail stream (image/png or image/webp).</returns>
    Task<Stream> DownloadThumbnailAsync(Guid jobId, CancellationToken cancellationToken = default);
}
