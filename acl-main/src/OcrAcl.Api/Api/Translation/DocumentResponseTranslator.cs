namespace OcrAcl.Api.Translation;

using OcrAcl.Api.Contracts;
using OcrAcl.Application.Models;
using OcrAcl.Application.Ports;

/// <summary>
/// Translates internal OCR job and document records to the FE document model.
/// Implements status mapping: pending→queued, processing→processing, completed→completed, failed→failed.
/// </summary>
public sealed class DocumentResponseTranslator
{
    /// <summary>
    /// Translates a <see cref="DocumentRecord"/> to the FE document response.
    /// </summary>
    /// <param name="record">The ACL document record.</param>
    /// <returns>The FE document response.</returns>
    public FeDocumentResponse Translate(DocumentRecord record)
    {
        return new FeDocumentResponse
        {
            Id = record.DocumentId,
            FileName = record.FileName,
            ContentType = record.ContentType,
            SizeBytes = record.SizeBytes,
            Status = record.Status.ToFeStatus(),
            CreatedAt = record.CreatedAt,
            CompletedAt = record.CompletedAt,
            PageCount = record.Result?.PageCount,
            Error = record.Error is not null ? TranslateError(record.Error) : null
        };
    }

    /// <summary>
    /// Translates an <see cref="OcrJob"/> to the FE document response.
    /// Used when the ACL store is not available (falls back to OCR job data only).
    /// Note: fileName, contentType, sizeBytes are not available from OCR job alone.
    /// </summary>
    /// <param name="job">The OCR job.</param>
    /// <param name="fileName">Original file name (from ACL state or upload).</param>
    /// <param name="contentType">MIME type (from ACL state or upload).</param>
    /// <param name="sizeBytes">File size in bytes (from ACL state or upload).</param>
    /// <returns>The FE document response.</returns>
    public FeDocumentResponse Translate(OcrJob job, string fileName, string contentType, long sizeBytes)
    {
        return new FeDocumentResponse
        {
            Id = job.JobId, // Per FE contract "generated by OCR" (INC-08), but ACL uses documentId per D-34
            FileName = fileName,
            ContentType = contentType,
            SizeBytes = sizeBytes,
            Status = job.Status.ToFeStatus(),
            CreatedAt = job.CreatedAt,
            CompletedAt = job.CompletedAt,
            PageCount = job.Result?.PageCount,
            Error = job.Error is not null ? TranslateError(job.Error) : null
        };
    }

    /// <summary>
    /// Translates an OCR job error to the FE error object (without documentId).
    /// </summary>
    /// <param name="error">OCR job error.</param>
    /// <returns>FE error object.</returns>
    private static FeErrorObject TranslateError(OcrJobError error)
    {
        // Map OCR error codes to FE error codes per D-42/D-36
        var feCode = error.Code switch
        {
            "PASSWORD_PROTECTED_PDF" => AclErrorCodes.OcrProcessingFailed,
            "CORRUPT_DOCUMENT" => AclErrorCodes.OcrProcessingFailed,
            "PROCESSING_TIMEOUT" => AclErrorCodes.OcrProcessingFailed,
            "ENGINE_ERROR" => AclErrorCodes.OcrProcessingFailed,
            "INVALID_FILE" => AclErrorCodes.InvalidFile,
            "UNSUPPORTED_MIME_TYPE" => AclErrorCodes.UnsupportedFileType,
            _ => AclErrorCodes.OcrProcessingFailed
        };

        return new FeErrorObject
        {
            Code = feCode,
            Message = error.Message,
            Details = new { ocrCode = error.Code }
        };
    }
}